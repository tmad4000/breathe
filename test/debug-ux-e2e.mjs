import assert from 'node:assert/strict';
import { launch } from './browser.mjs';
const base = process.argv[2] ?? 'http://127.0.0.1:8793/';
const browser = await launch();
const errors=[];
try {
 const page=await browser.newPage({viewport:{width:390,height:844}});
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(base);
 await page.click('#modeTabs [data-mode=guide]');
 await page.click('#startBtn');
 await page.waitForTimeout(300);
 assert.equal(await page.locator('#modeSelect').isEnabled(),true);
 await page.click('#pauseBtn');
 assert.equal(await page.locator('#modeTabs').isVisible(),true);
 await page.selectOption('#quickPattern','5-0-5');
 assert.match(await page.locator('#switchNotice').textContent(),/Pattern changes/);
 await page.click('#undoChange');
 assert.equal(await page.inputValue('#quickPattern'),'5-1-5-1');
 await page.click('#modeTabs [data-mode=respiration]');
 assert.equal(await page.locator('#startBtn').isVisible(),true,'paused switch goes ready');
 const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('breathe.sessions.v1')));
 assert.equal(saved.length,1,'short session saved on mode switch');
 assert.equal(saved[0].mode,'guide');
 assert.match(await page.title(),/Respiration Tracker/);
 await page.selectOption('#quickPace','12');
 assert.equal(await page.inputValue('#paceSelect'),'12');
 await page.click('#guideToneBtn');
 assert.equal(await page.getAttribute('#guideToneBtn','aria-pressed'),'false');
 await page.click('#detectionToneBtn');
 assert.equal(await page.getAttribute('#detectionToneBtn','aria-pressed'),'true');
 assert.equal(await page.isChecked('#ownSoundToggle'),true);
 await page.click('#modeTabs [data-mode=guide]');
 await page.click('#startBtn');
 await page.selectOption('#modeSelect','coach');
 await page.waitForFunction(()=>window.__breathe.coach?.adaptive);
 assert.equal(await page.locator('#pauseBtn').isVisible(),true,'running switch continues');
 await page.waitForTimeout(300);
 assert.equal(await page.locator('#trackingNotice').isVisible(),true,'coach says guide-only if camera denied');
 await page.click('#stopBtn');
 assert.deepEqual(errors,[]);
 console.log('PASS: paused/running switching, short save, pattern Undo, on-screen pace and tones, advisory status');
} finally { await browser.close(); }
